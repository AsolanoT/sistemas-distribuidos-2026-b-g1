import { act, fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { apiClient } from '../../test-doubles/shellApiClient'
import { session } from '../../test-doubles/shellSession'
import { SalesPage } from './SalesPage'

const customer = '12345678-1234-4234-8234-123456789abc'
const sale = { saleId: '12345678-1234-4234-8234-123456789abd', customerId: customer, createdBy: 'server-scoped', date: '2026-10-12T01:00:00Z', totalCents: 123456789, active: true, details: [{ detailId: 'line', productId: 'product', quantity: 1, unitPriceCents: 7, subtotalCents: 7, active: true }] }
const page = (data = [sale], number = 1, totalPages = 3) => ({ data, meta: { page: number, limit: 20, total: totalPages ? 41 : 0, totalPages } })
const failure = (status: number, error = 'INTERNAL_ERROR') => ({ status, body: { error, message: 'Raw English backend failure', traceId: 'trace-example' } })
function deferred() {
  let resolve!: (value: unknown) => void
  let reject!: (error: unknown) => void
  const promise = new Promise((yes, no) => { resolve = yes; reject = no })
  return { promise, resolve, reject }
}
beforeEach(() => {
  apiClient.request.mockReset().mockResolvedValue(page())
  session.user.mockReset().mockReturnValue({ sub: 'identity', role: 'ADMIN' })
})
const ready = () => screen.findByRole('region', { name: 'Tabla de ventas' })

it('loading conserva encabezado y filtros, anuncia y muestra filas skeleton sin ventas', () => {
  apiClient.request.mockReturnValue(new Promise(() => {}))
  render(<SalesPage />)
  expect(screen.getByRole('heading', { name: 'Ventas' })).toBeVisible()
  expect(screen.getByLabelText('Desde')).toBeVisible()
  expect(screen.getAllByRole('status').find((element) => element.textContent === 'Cargando ventas…')).toBeVisible()
  expect(screen.getByRole('table')).toHaveAttribute('aria-busy', 'true')
  expect(screen.queryByText(customer)).toBeNull()
})
it.each(['ADMIN', 'SALESPERSON'])('data %s usa respuesta y total autoritativo', async (role) => {
  session.user.mockReturnValue({ sub: 'identity', role })
  render(<SalesPage />)
  const table = await ready()
  expect(within(table).getAllByRole('columnheader').map((cell) => cell.textContent)).toEqual(['Fecha', 'Cliente', 'Líneas', 'Total', 'Acciones'])
  expect(screen.getByText(customer)).toBeVisible()
  expect(screen.getByText(/1\.234\.567,89/)).toBeVisible()
  expect(screen.getByText(/11.*2026/)).toBeVisible()
  expect(screen.getByRole('link', { name: `Ver venta ${sale.saleId}` })).toHaveAttribute('href', `/sales/${sale.saleId}`)
  expect(screen.queryByText(/estará disponible en una próxima entrega/)).toBeNull()
  // Opening /sales still asks only for the history: the form never preloads Customers or Products.
  expect(apiClient.request.mock.calls.every(([path]) => path === '/api/v1/sales')).toBe(true)
  expect(session.user).toHaveBeenCalled()
})
it('error y retry conservan filtros y página e incluyen trace sin mensaje inglés', async () => {
  const user = userEvent.setup()
  render(<SalesPage />)
  await ready()
  await user.type(screen.getByLabelText('ID del cliente'), customer)
  await user.click(screen.getByRole('button', { name: 'Aplicar filtros' }))
  await ready()
  apiClient.request.mockRejectedValueOnce(failure(0, 'NETWORK_ERROR'))
  await user.click(screen.getByRole('button', { name: 'Siguiente' }))
  expect(await screen.findByRole('alert')).toHaveTextContent('No se pudo cargar el historial de ventas.')
  expect(screen.getByRole('alert')).toHaveTextContent('trace-example')
  expect(screen.queryByText(/Raw English/)).toBeNull()
  const query = apiClient.request.mock.lastCall?.[1]?.query
  apiClient.request.mockResolvedValue(page([sale], 2))
  await user.click(screen.getByRole('button', { name: 'Reintentar' }))
  await ready()
  expect(apiClient.request.mock.lastCall?.[1]?.query).toEqual(query)
  expect(screen.getByLabelText('ID del cliente')).toHaveValue(customer)
})
it.each([[401, 'La sesión ha finalizado.'], [403, 'No tienes permiso para consultar el historial de ventas.']])('distingue %s sin datos ni retry automático', async (status, copy) => {
  apiClient.request.mockRejectedValue(failure(status as number))
  render(<SalesPage />)
  expect(await screen.findByRole('alert')).toHaveTextContent(copy as string)
  expect(screen.queryByRole('button', { name: 'Reintentar' })).toBeNull()
  expect(screen.queryByText(customer)).toBeNull()
  expect(apiClient.request).toHaveBeenCalledTimes(1)
})
it.each(['TIMEOUT', 'NETWORK_ERROR'])('muestra error de conexión %s', async (code) => {
  apiClient.request.mockRejectedValue(failure(0, code))
  render(<SalesPage />)
  expect(await screen.findByRole('alert')).toHaveTextContent('No se pudo conectar con el servidor.')
})
it('empty sin filtros ofrece recarga y cero páginas no ofrece navegación inválida', async () => {
  apiClient.request.mockResolvedValue(page([], 1, 0))
  const user = userEvent.setup()
  render(<SalesPage />)
  expect(await screen.findByText('No hay ventas registradas todavía.')).toBeVisible()
  expect(screen.queryByRole('button', { name: 'Siguiente' })).toBeNull()
  await user.click(screen.getByRole('button', { name: 'Recargar historial' }))
  await waitFor(() => expect(apiClient.request).toHaveBeenCalledTimes(2))
})
it('empty filtrado permite limpiar y restablecer los campos', async () => {
  apiClient.request.mockResolvedValue(page([], 1, 0))
  const user = userEvent.setup()
  render(<SalesPage />)
  await user.type(screen.getByLabelText('ID del cliente'), customer)
  await user.click(screen.getByRole('button', { name: 'Aplicar filtros' }))
  expect(await screen.findByText('Ninguna venta coincide con estos filtros.')).toBeVisible()
  await user.click(screen.getByRole('button', { name: 'Limpiar filtros del historial' }))
  expect(await screen.findByText('No hay ventas registradas todavía.')).toBeVisible()
  expect(screen.getByLabelText('ID del cliente')).toHaveValue('')
  expect(apiClient.request.mock.lastCall?.[1]?.query).toEqual({ page: 1, limit: 20 })
})
it('paginación usa meta, conserva filtros y nuevos filtros vuelven a página 1', async () => {
  const user = userEvent.setup()
  apiClient.request.mockImplementation((_path, options) => Promise.resolve(page([sale], Number(options?.query?.page))))
  render(<SalesPage />)
  await ready()
  expect(screen.getByRole('button', { name: 'Anterior' })).toBeDisabled()
  await user.click(screen.getByRole('button', { name: 'Siguiente' }))
  await screen.findByText(/Página 2 de 3/)
  fireEvent.change(screen.getByLabelText('Desde'), { target: { value: '2026-09-01' } })
  fireEvent.change(screen.getByLabelText('Hasta'), { target: { value: '2026-09-30' } })
  await user.click(screen.getByRole('button', { name: 'Aplicar filtros' }))
  await ready()
  expect(apiClient.request.mock.lastCall?.[1]?.query).toEqual({ page: 1, limit: 20, from: '2026-09-01', to: '2026-09-30' })
  await user.click(screen.getByRole('button', { name: 'Siguiente' }))
  await ready()
  expect(apiClient.request.mock.lastCall?.[1]?.query?.from).toBe('2026-09-01')
  await user.click(screen.getByRole('button', { name: 'Siguiente' }))
  await screen.findByText(/Página 3 de 3/)
  expect(screen.getByRole('button', { name: 'Siguiente' })).toBeDisabled()
  await user.click(screen.getByRole('button', { name: 'Anterior' }))
  await screen.findByText(/Página 2 de 3/)
})
it('rechaza UUID y rango inválidos con descripciones asociadas sin pedir datos', async () => {
  const user = userEvent.setup()
  render(<SalesPage />)
  await ready()
  await user.type(screen.getByLabelText('ID del cliente'), 'invalid')
  fireEvent.change(screen.getByLabelText('Desde'), { target: { value: '2026-10-10' } })
  fireEvent.change(screen.getByLabelText('Hasta'), { target: { value: '2026-10-01' } })
  await user.click(screen.getByRole('button', { name: 'Aplicar filtros' }))
  expect(screen.getByLabelText('ID del cliente')).toHaveAttribute('aria-invalid', 'true')
  expect(screen.getByLabelText('ID del cliente')).toHaveAccessibleDescription(/UUID/)
  expect(screen.getByLabelText('Hasta')).toHaveAccessibleDescription(/posterior/)
  expect(screen.getByLabelText('Hasta')).toHaveFocus()
  expect(apiClient.request).toHaveBeenCalledTimes(1)
})
it('teclado: etiquetas, formulario Enter y scroll de tabla accesible', async () => {
  const user = userEvent.setup()
  render(<SalesPage />)
  await ready()
  screen.getByLabelText('Desde').focus()
  expect(screen.getByLabelText('Desde')).toHaveFocus()
  await user.tab()
  expect(screen.getByLabelText('Hasta')).toHaveFocus()
  await user.tab()
  expect(screen.getByLabelText('ID del cliente')).toHaveFocus()
  await user.type(screen.getByLabelText('ID del cliente'), `${customer}{Enter}`)
  await ready()
  expect(apiClient.request.mock.lastCall?.[1]?.query?.customerId).toBe(customer)
  expect(screen.getByRole('region', { name: 'Tabla de ventas' })).toHaveAttribute('tabindex', '0')
})
it('cancela y descarta respuestas anteriores que llegan después de la nueva', async () => {
  const slow = deferred()
  const fast = deferred()
  apiClient.request.mockReturnValueOnce(slow.promise).mockReturnValueOnce(fast.promise)
  const user = userEvent.setup()
  const { unmount } = render(<SalesPage />)
  await user.type(screen.getByLabelText('ID del cliente'), customer)
  await user.click(screen.getByRole('button', { name: 'Aplicar filtros' }))
  expect(apiClient.request.mock.calls[0][1]?.signal?.aborted).toBe(true)
  await act(async () => fast.resolve(page([{ ...sale, totalCents: 7 }])))
  await act(async () => slow.resolve(page()))
  expect(screen.getByText(/0,07/)).toBeVisible()
  expect(screen.queryByText(/1\.234\.567,89/)).toBeNull()
  unmount()
  expect(apiClient.request.mock.lastCall?.[1]?.signal?.aborted).toBe(true)
})
it('cancelación rechazada no se vuelve error visible', async () => {
  const slow = deferred()
  apiClient.request.mockReturnValueOnce(slow.promise).mockResolvedValueOnce(page())
  const user = userEvent.setup()
  render(<SalesPage />)
  await user.click(screen.getByRole('button', { name: 'Aplicar filtros' }))
  await ready()
  await act(async () => slow.reject(failure(0, 'CANCELLED')))
  expect(screen.queryByRole('alert')).toBeNull()
})
